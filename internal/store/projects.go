// Project is a first-class project: the row behind the free-text `project` tag
// that runs, lanes and decisions carry. The tag stays the join key (there are
// no foreign keys), so a project can exist as a tag before it has a row and a
// row can exist before anything is tagged with it — the two converge because
// EnsureProject registers a bare row whenever a tagged item is created.
//
// The column set converges with the data-engineering line's `projects` table so
// the same database can serve both (see migrations/0022_projects.sql).
type Project struct {
	ID   string `json:"id"`
	Name string `json:"name"`
	// Summary is HUMAN-OWNED: "what this project is for", typed by the person
	// who started it and never written by the platform. It was briefly both
	// this and the machine narrative, which is how accepting a delivery came to
	// overwrite an owner's description; `Narrative` is the other half now.
	Summary string `json:"summary,omitempty"`
	// Narrative is MACHINE-WRITTEN: "what this project has built so far",
	// regenerated by internal/brief from the briefs of accepted deliveries.
	// Empty means nothing has been accepted yet — never the owner's words.
	Narrative string `json:"narrative,omitempty"`
	// Declarations is the project's declaration document: an extensible set of
	// typed groups (purpose, datasets, environment today) that recipe slots
	// inherit from. Carried as raw JSON so a group this build does not know
	// about survives a read-modify-write. See declarations.go.
	Declarations JSON      `json:"declarations,omitempty"`
	Status       string    `json:"status"`
	Owner        string    `json:"owner,omitempty"`
	Provenance   string    `json:"provenance"`
	CreatedAt    time.Time `json:"createdAt"`
	UpdatedAt    time.Time `json:"updatedAt"`
}

// Provenance values. Main only ever writes "user"; the others exist because the
// data-engineering line writes them and its CHECK constraint enumerates them.
const (
	ProjectProvenanceUser     = "user"
	ProjectProvenanceDemo     = "demo"
	ProjectProvenanceImported = "imported"
	ProjectProvenanceTest     = "test"
)

const projectCols = `id, name, summary, narrative, declarations, status, owner, provenance, created_at, updated_at`

// UnscopedProject is the empty project tag: the bucket every untagged run,
// lane and decision falls into. It is a FILTER, never a project — it has no
// row, cannot be created, and must not be offered anywhere a project is picked.
const UnscopedProject = ""

// UnscopedProjectName is the display name ListProjects gives that bucket. The
// aggregate row has no `projects` row to take a name from, and shipping it
// nameless is what made it render as a blank card; naming it here means every
// reader (web chips, the Projects panel, the CLI table) says the same word.
const UnscopedProjectName = "Unscoped"

func scanProject(row pgx.Row) (Project, error) {
	var p Project
	err := row.Scan(&p.ID, &p.Name, &p.Summary, &p.Narrative, &p.Declarations,
		&p.Status, &p.Owner, &p.Provenance, &p.CreatedAt, &p.UpdatedAt)
	return p, err
}

// ProjectCount is one project as the selector and the Projects surface see it:
// the tag, the combined item count, the per-kind breakdown, and the registered
// row's metadata when there is one.
//
// `Project` and `Count` are the original two fields and keep their meaning, so
// existing consumers (the project chips) are unaffected by the extra fields.
// A row with Registered=false is a project that exists only as a tag — that
// cannot normally happen once EnsureProject is in play, but a database written
// by an older build (or by hand) still reports honestly.
type ProjectCount struct {
	Project string `json:"project"`
	Count   int    `json:"count"`

	// Registered row metadata (zero when Registered is false).
	Registered bool   `json:"registered"`
	Name       string `json:"name,omitempty"`
	Summary    string `json:"summary,omitempty"`
	// Narrative and Declarations mirror the row's columns so a card and a
	// recipe form can render both halves of a project without a second fetch.
	Narrative    string `json:"narrative,omitempty"`
	Declarations JSON   `json:"declarations,omitempty"`
	Status       string `json:"status,omitempty"`
	Provenance   string `json:"provenance,omitempty"`

	// Per-kind breakdown of Count, plus the number of distinct workflows
	// that have run under the tag. WorkflowCount is deliberately not
	// called "workflows": ProjectDetail embeds this struct and carries the
	// workflow LIST under that name.
	Runs          int `json:"runs"`
	Lanes         int `json:"lanes"`
	Decisions     int `json:"decisions"`
	WorkflowCount int `json:"workflowCount"`

	// LastActivity is the newest run/lane/decision timestamp, falling back to
	// the project row's updated_at when nothing is tagged yet.
	LastActivity *time.Time `json:"lastActivity,omitempty"`
}

// ProjectWorkflow is one workflow a project has actually run: a DAG, plus the
// recipe it was instantiated from when the run carries one. This is derived
// from runs rather than declared, so it never claims a workflow belongs to a
// project that has not run it.
type ProjectWorkflow struct {
	Key  string `json:"key"`
	Name string `json:"name"`
	DAG  string `json:"dag"`
	// Recipe is the template ID a run was instantiated from — a uuid, which is
	// what the run doc stamps. RecipeName is that template's display name,
	// resolved here so no surface has to render a 36-character code where a
	// name belongs. Empty when the template has since been deleted.
	Recipe     string `json:"recipe,omitempty"`
	RecipeName string `json:"recipeName,omitempty"`
	Runs       int    `json:"runs"`
	// RealRuns is how many of those runs were NOT rehearsals. It is what the
	// recipe form asks before deciding whether to pre-tick Dry run: the first
	// time a recipe is run under a project, a rehearsal is the cheaper mistake,
	// and after one real run the person has seen what it does.
	RealRuns int `json:"realRuns"`
	// SourceWorkflowID names the saved workflow this group belongs to, so a row
	// can link to it without any surface parsing the key. Empty for a group with
	// no saved source.
	SourceWorkflowID string     `json:"sourceWorkflowId,omitempty"`
	LastRunID        string     `json:"lastRunId,omitempty"`
	LastState        string     `json:"lastState,omitempty"`
	LastRunAt        *time.Time `json:"lastRunAt,omitempty"`
}

// ProjectDetail is a project's summary row plus the workflows it has run. The
// items themselves (runs, lanes, decisions) are read through their own
// project-filtered endpoints rather than duplicated here.
type ProjectDetail struct {
	ProjectCount
	Workflows []ProjectWorkflow `json:"workflows"`
	// SlotDefaults is what this project's declarations can fill in on a recipe
	// form, keyed by ContextSlot id, each carrying the declaration path it came
	// from. Resolved server-side so the slot→declaration mapping lives in one
	// place (store.slotInheritance) rather than once per client.
	// A prefill that only makes sense on ONE recipe is keyed "<recipe>/<slot>"
	// (store.ScopedSlotKey): `grain` is the audited dataset's grain in
	// data-quality-audit and the finished table's grain in data-pipeline, and a
	// dataset answers the first and not the second. Read a slot with
	// store.LookupPrefill, or its TypeScript twin, so the scoped answer wins.
	SlotDefaults map[string]SlotPrefill `json:"slotDefaults,omitempty"`
	// SlotNotes is what the project says about the slots it deliberately leaves
	// EMPTY: which window is under test, which dashboard a side reads. They are
	// the honest half of what positional inheritance used to assert.
	SlotNotes map[string]string `json:"slotNotes,omitempty"`
}

// defaultProjectName turns a project tag into a display name the same way the
// migration backfill does (INITCAP over hyphen/underscore-separated words), so
// a row registered by Go and a row backfilled by SQL look identical.
func defaultProjectName(id string) string {
	words := strings.FieldsFunc(id, func(r rune) bool { return r == '-' || r == '_' || r == ' ' })
	for i, w := range words {
		words[i] = strings.ToUpper(w[:1]) + strings.ToLower(w[1:])
	}
	if len(words) == 0 {
		return id
	}
	return strings.Join(words, " ")
}

// EnsureProject registers a bare project row for a tag value, so the projects
// table stays in sync with what is actually tagged. It is the auto-register
// hook called from every write that carries a project tag (CreateRun,
// CreateLane, UpsertDecision).
//
// The empty tag means "unscoped" and never becomes a row. Existing rows are
// left completely alone: this deliberately does NOT bump updated_at, because
// the Projects surface orders by activity and a re-registration is not an edit.
func (s *Store) EnsureProject(ctx context.Context, id string) error {
	id = strings.TrimSpace(id)
	if id == "" {
		return nil
	}
	_, err := s.Pool.Exec(ctx, `
		INSERT INTO projects (id, name) VALUES ($1, $2)
		ON CONFLICT (id) DO NOTHING`, id, defaultProjectName(id))
	if err != nil {
		return fmt.Errorf("ensure project %q: %w", id, err)
	}
	return nil
}

// ListProjects returns every project — registered rows AND any tag still in use
// without one — with a combined item count across decisions, runs and lanes,
// most recently active first.
//
// This is a FULL OUTER JOIN rather than the inner join the data-engineering
// line uses, because main keeps TAG semantics: a project that has a row but no
// items yet must still be listed (that is the point of the table), and a tag
// with items but no row must not silently disappear. The unscoped tag ("")
// keeps its row in the result, as it always has.
//
// includeTest keeps provenance='test' rows, which only a shared database
// written by the data-engineering line's fixtures will have.
func (s *Store) ListProjects(ctx context.Context, includeTest bool) ([]ProjectCount, error) {
	registered := `SELECT ` + projectCols + ` FROM projects`
	if !includeTest {
		registered += ` WHERE provenance <> '` + ProjectProvenanceTest + `'`
	}
	rows, err := s.Pool.Query(ctx, `
		WITH activity AS (
			SELECT project,
				SUM(runs)::bigint      AS runs,
				SUM(lanes)::bigint     AS lanes,
				SUM(decisions)::bigint AS decisions,
				SUM(workflows)::bigint AS workflows,
				MAX(u)                 AS last_activity
			FROM (
				SELECT project, 0 AS runs, 0 AS lanes, COUNT(*) AS decisions, 0 AS workflows,
					MAX(updated_at) AS u
					FROM decisions GROUP BY project
				UNION ALL
				-- The count is the rows the project detail lists, no more and no
				-- less. Runs contribute every group EXCEPT those the library
				-- already counts below — a group whose saved workflow still
				-- exists in this project — so a workflow is never counted twice
				-- and a group whose saved source was deleted is not lost.
				SELECT r.project, COUNT(*), 0, 0,
					COUNT(DISTINCT k.key) FILTER (WHERE w.id IS NULL), MAX(r.updated_at)
					FROM runs r
					CROSS JOIN LATERAL (SELECT project_workflow_identity(r.options,r.dag,r.goal,r.doc)->>'key' AS key) k
					LEFT JOIN sdk_workflows w ON 'saved:' || w.id = k.key AND w.project = r.project
					GROUP BY r.project
				UNION ALL
				-- A saved workflow IS one of its project's workflows, whether or
				-- not it has ever run. Reading "WORKFLOWS 0" right after saving
				-- one was the project surface contradicting the library.
				SELECT project, 0, 0, 0, COUNT(*), MAX(updated_at)
					FROM sdk_workflows GROUP BY project
				UNION ALL
				SELECT project, 0, COUNT(*), 0, 0, MAX(created_at)
					FROM lanes GROUP BY project
			) per_kind
			GROUP BY project
		), registered AS (`+registered+`)
		SELECT
			COALESCE(r.id, a.project)                                             AS project,
			COALESCE(a.runs, 0) + COALESCE(a.lanes, 0) + COALESCE(a.decisions, 0) AS count,
			(r.id IS NOT NULL)                                                    AS registered,
			COALESCE(r.name, '')                                                  AS name,
			COALESCE(r.summary, '')                                               AS summary,
			COALESCE(r.narrative, '')                                             AS narrative,
			COALESCE(r.declarations, '{}'::jsonb)                                 AS declarations,
			COALESCE(r.status, '')                                                AS status,
			COALESCE(r.provenance, '')                                            AS provenance,
			COALESCE(a.runs, 0)                                                   AS runs,
			COALESCE(a.lanes, 0)                                                  AS lanes,
			COALESCE(a.decisions, 0)                                              AS decisions,
			COALESCE(a.workflows, 0)                                              AS workflows,
			COALESCE(a.last_activity, r.updated_at)                               AS last_activity
		FROM activity a
		FULL OUTER JOIN registered r ON r.id = a.project
		ORDER BY COALESCE(a.last_activity, r.updated_at) DESC NULLS LAST, COALESCE(r.id, a.project)`)
	if err != nil {
		return nil, fmt.Errorf("list projects: %w", err)
	}
	defer rows.Close()
	var out []ProjectCount
	for rows.Next() {
		var pc ProjectCount
		if err := rows.Scan(&pc.Project, &pc.Count, &pc.Registered, &pc.Name, &pc.Summary,
			&pc.Narrative, &pc.Declarations,
			&pc.Status, &pc.Provenance, &pc.Runs, &pc.Lanes, &pc.Decisions, &pc.WorkflowCount,
			&pc.LastActivity); err != nil {
			return nil, fmt.Errorf("scan project: %w", err)
		}
		out = append(out, shapeUnscoped(pc))
	}
	return out, rows.Err()
}

// shapeUnscoped labels the empty-tag aggregate. Registered stays false — there
// genuinely is no row, and callers use that to keep the bucket out of any
// picker — but it gets a name so nothing has to render it as a blank.
func shapeUnscoped(pc ProjectCount) ProjectCount {
	if pc.Project == UnscopedProject && pc.Name == "" {
		pc.Name = UnscopedProjectName
	}
	return pc
}

// GetProject returns one registered project row.
func (s *Store) GetProject(ctx context.Context, id string) (Project, error) {
	row := s.Pool.QueryRow(ctx, `SELECT `+projectCols+` FROM projects WHERE id=$1`, id)
	p, err := scanProject(row)
	if errors.Is(err, pgx.ErrNoRows) {
		return p, ErrNotFound
	}
	if err != nil {
		return p, fmt.Errorf("get project %q: %w", id, err)
	}
	return p, nil
}

// CreateProject inserts a new project. Insert-only: an existing id is
// ErrExists, so creating never silently overwrites someone's description.
func (s *Store) CreateProject(ctx context.Context, p Project) (Project, error) {
	p.ID = strings.TrimSpace(p.ID)
	if p.ID == "" {
		return Project{}, fmt.Errorf("create project: id is required")
	}
	if p.Name == "" {
		p.Name = defaultProjectName(p.ID)
	}
	if p.Status == "" {
		p.Status = "active"
	}
	if len(p.Declarations) == 0 {
		p.Declarations = JSON(EmptyDeclarations)
	}
	if err := refuseNewDeclarationProblems(JSON(EmptyDeclarations), p.Declarations); err != nil {
		return Project{}, err
	}
	// A project is never created with a narrative: "what this project has built
	// so far" is written from accepted deliveries, and there are none yet.
	row := s.Pool.QueryRow(ctx, `
		INSERT INTO projects (id, name, summary, declarations, status, owner)
		VALUES ($1,$2,$3,$4,$5,$6)
		ON CONFLICT (id) DO NOTHING
		RETURNING `+projectCols,
		p.ID, p.Name, p.Summary, p.Declarations, p.Status, p.Owner)
	out, err := scanProject(row)
	if errors.Is(err, pgx.ErrNoRows) {
		return out, ErrExists
	}
	if err != nil {
		return out, fmt.Errorf("create project %q: %w", p.ID, err)
	}
	return out, nil
}

// ProjectPatch is a partial edit: a nil field is "leave it alone", which is
// what lets PATCH change a description without resending the name.
type ProjectPatch struct {
	Name    *string `json:"name,omitempty"`
	Summary *string `json:"summary,omitempty"`
	// Narrative is the machine-written half. It has a patch field because the
	// brief writer is the one that sets it — no human-facing form offers it.
	Narrative *string `json:"narrative,omitempty"`
	// Declarations is merged GROUP BY GROUP rather than replaced, so a client
	// that only knows about `datasets` cannot delete a group it has never heard
	// of. See MergeDeclarations.
	Declarations *JSON   `json:"declarations,omitempty"`
	Status       *string `json:"status,omitempty"`
	Owner        *string `json:"owner,omitempty"`
}

// UpdateProject applies a partial edit and bumps updated_at.
//
// A declarations patch is merged into the stored document rather than replacing
// it: the groups the patch names are overwritten, every other group is left
// byte-for-byte alone. That is what keeps the document extensible — a form that
// edits `datasets` cannot destroy a `kpis` group added by a later build.
func (s *Store) UpdateProject(ctx context.Context, id string, patch ProjectPatch) (Project, error) {
	var declarations *JSON
	if patch.Declarations != nil {
		current, err := s.GetProject(ctx, id)
		if err != nil {
			return Project{}, err
		}
		merged, err := MergeDeclarations(current.Declarations, *patch.Declarations)
		if err != nil {
			return Project{}, fmt.Errorf("update project %q: %w", id, err)
		}
		// The PATCH path is the one the declaration form actually uses, which
		// is how a tolerance with a unit and no number reached a project while
		// the sentence refusing it already existed and ran nowhere.
		if err := refuseNewDeclarationProblems(current.Declarations, merged); err != nil {
			return Project{}, err
		}
		declarations = &merged
	}
	row := s.Pool.QueryRow(ctx, `
		UPDATE projects SET
			name         = COALESCE($2, name),
			summary      = COALESCE($3, summary),
			narrative    = COALESCE($4, narrative),
			declarations = COALESCE($5, declarations),
			status       = COALESCE($6, status),
			owner        = COALESCE($7, owner),
			updated_at   = NOW()
		WHERE id=$1
		RETURNING `+projectCols,
		id, patch.Name, patch.Summary, patch.Narrative, declarations, patch.Status, patch.Owner)
	p, err := scanProject(row)
	if errors.Is(err, pgx.ErrNoRows) {
		return p, ErrNotFound
	}
	if err != nil {
		return p, fmt.Errorf("update project %q: %w", id, err)
	}
	return p, nil
}

// ListProjectWorkflows groups saved-source associations or frozen SDK definitions.
// Both overview counts and this list use project_workflow_identity.
func (s *Store) ListProjectWorkflows(ctx context.Context, project string) ([]ProjectWorkflow, error) {
	rows, err := s.Pool.Query(ctx, `
 WITH identified AS MATERIALIZED (
   SELECT dag, COALESCE(doc->>'recipe','') AS recipe, run_id, state, updated_at, mode,
          project_workflow_identity(options,dag,goal,doc) AS identity
   FROM runs WHERE project=$1
 ), ranked AS (
   SELECT *, COUNT(*) OVER (PARTITION BY identity->>'key') AS cnt,
      COUNT(*) FILTER (WHERE LOWER(BTRIM(COALESCE(mode,''))) <> ALL($2)) OVER (PARTITION BY identity->>'key') AS real_cnt,
      ROW_NUMBER() OVER (PARTITION BY identity->>'key' ORDER BY updated_at DESC,run_id DESC) AS rn
   FROM identified
 ) SELECT identity->>'key', identity->>'name',dag,recipe,cnt,real_cnt,run_id,state,updated_at,
        COALESCE(identity->>'sourceWorkflowId','')
 FROM ranked WHERE rn=1 ORDER BY updated_at DESC,run_id DESC`, project, RehearsalModes)
	if err != nil {
		return nil, fmt.Errorf("list project workflows: %w", err)
	}
	defer rows.Close()
	var out []ProjectWorkflow
	for rows.Next() {
		var wf ProjectWorkflow
		if err := rows.Scan(&wf.Key, &wf.Name, &wf.DAG, &wf.Recipe, &wf.Runs, &wf.RealRuns,
			&wf.LastRunID, &wf.LastState, &wf.LastRunAt, &wf.SourceWorkflowID); err != nil {
			return nil, fmt.Errorf("scan project workflow: %w", err)
		}
		out = append(out, wf)
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}
	// The name comes from the ONE resolver, not from a join local to this
	// query: the join here answered "dataset-shift-audit" while the brief and
	// the run page were still printing the template's UUID, which is exactly
	// how one fix reached one surface out of four.
	namer, _ := s.NewRecipeNamer(ctx)
	for i := range out {
		out[i].RecipeName = namer.Name(out[i].Recipe)
	}
	// A saved workflow that has never run is still one of this project's
	// workflows. Leaving it out told a person who had just saved one that the
	// project held nothing — so it is listed with the zero it honestly has.
	ran := map[string]bool{}
	for _, wf := range out {
		ran[wf.Key] = true
	}
	saved, err := s.Pool.Query(ctx, `SELECT id,name FROM sdk_workflows WHERE project=$1 ORDER BY lower(name),id`, project)
	if err != nil {
		return nil, fmt.Errorf("list saved workflows for %q: %w", project, err)
	}
	defer saved.Close()
	for saved.Next() {
		var id, name string
		if err := saved.Scan(&id, &name); err != nil {
			return nil, err
		}
		if key := SavedWorkflowKey(id); !ran[key] {
			out = append(out, ProjectWorkflow{Key: key, Name: name, SourceWorkflowID: id})
		}
	}
	if err := saved.Err(); err != nil {
		return nil, err
	}
	return out, nil
}

// GetProjectDetail returns a project's summary row (counts included) plus the
// workflows it has run. Returns ErrNotFound when the id is neither a
// registered project nor a tag in use.
func (s *Store) GetProjectDetail(ctx context.Context, id string) (ProjectDetail, error) {
	var detail ProjectDetail
	// includeTest=true: asking for a project by id should find it whatever its
	// provenance — the filter is about what the list surfaces, not existence.
	all, err := s.ListProjects(ctx, true)
	if err != nil {
		return detail, err
	}
	found := false
	for _, pc := range all {
		if pc.Project == id {
			detail.ProjectCount = pc
			found = true
			break
		}
	}
	if !found {
		return detail, ErrNotFound
	}
	wfs, err := s.ListProjectWorkflows(ctx, id)
	if err != nil {
		return detail, err
	}
	if wfs == nil {
		wfs = []ProjectWorkflow{}
	}
	detail.Workflows = wfs
	decl, err := ParseDeclarations(detail.Declarations)
	if err != nil {
		// A declaration document that will not parse is worth reporting on the
		// project it belongs to, not worth failing every read of the project.
		return detail, nil
	}
	if prefill := PrefillSlots(decl); len(prefill) > 0 {
		detail.SlotDefaults = prefill
	}
	detail.SlotNotes = SlotNotes(decl)
	return detail, nil
}
